"""advisor 只读端口（编译期形状；ADR-0013 D3）。

- `ReadModel`：账本/目标/配置/信号的**只读数字视图**（实现见 `read.py`）。
- `LlmGateway`：JSON 输出的唯一 LLM 入口（W4 注入实现）。
本模块只有 Protocol，无实现、无 DB、无网络。
"""
from typing import Any, Protocol


class ReadModel(Protocol):
    """advisor 可用的全部读数（禁止写端口）。"""

    def net_worth(self, as_of=None) -> dict: ...
    def appreciation(self, as_of=None) -> dict: ...
    def returns(self, as_of=None) -> dict: ...
    def goal_progress(self, as_of=None, goal_id=None) -> dict | None: ...
    def goal_version_as_of(self, goal_id: int, as_of) -> dict | None: ...
    def allocation_rows_as_of(self, as_of) -> dict: ...
    def allocation_rows(self, as_of=None) -> list[dict]: ...
    def signals(self, as_of=None) -> dict: ...


class LlmGateway(Protocol):
    """LLM 网关：只吃 prompt、只吐结构化 JSON（不做算术/判灯）。"""

    def complete_json(self, *, prompt: str, schema: dict,
                      model: str | None = None) -> dict[str, Any]: ...